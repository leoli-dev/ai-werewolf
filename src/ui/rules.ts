export function showRules(root: HTMLElement) {
  const back = h(
    'div',
    { class: 'modal-back', onclick: (e: Event) => e.target === back && back.remove() },
    h(
      'div',
      { class: 'modal panel', role: 'dialog', 'aria-label': '游戏规则' },
      h('h1', {}, '规则说明'),
      ...SECTIONS.flatMap(([title, items]) => [h('h2', {}, title), h('ul', {}, ...items.map((t) => h('li', {}, t)))]),
      h('div', { class: 'actions' }, h('button', { class: 'btn primary', onclick: () => back.remove() }, '明白了')),
    ),
  );
  root.appendChild(back);
}
